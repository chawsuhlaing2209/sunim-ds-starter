#!/usr/bin/env node
/**
 * Assembles the stylesheet a consumer imports.
 *
 * Vite emits the components' own CSS. That CSS is nothing but `var(--token)`
 * references, so on its own it renders every component unstyled — not broken,
 * not erroring, just wrong, which is the slowest kind of failure to trace. The
 * token layer has to come first, in the same file, or the package ships a
 * stylesheet that quietly does nothing.
 *
 * Two files come out:
 *
 *   dist/styles.css   tokens + components. The one import, and the common path.
 *   dist/tokens.css   the token layer alone, for a consumer building their own
 *                     components against this system rather than using ours.
 *
 * Order matters and is not negotiable: tokens define the custom properties,
 * components consume them, and a cascade cannot read forwards.
 *
 * It also ships the typefaces, which it did not always do. The first version of
 * this file emitted a stylesheet naming `"Schibsted Grotesk"` twenty-eight times
 * and carrying no `@font-face` and no font file — so every consumer got the
 * browser's default serif and no error. Storybook and the reference site both
 * looked correct throughout, because each imports the fonts itself; the package
 * was the one surface with no imports of its own, which is exactly why nobody
 * saw it.
 *
 * Which faces ship is derived from the tokens rather than listed here. Add a
 * weight in Figma, re-export, and the face follows it into the bundle — the same
 * loop everything else in this repo runs on, and the only version of this that
 * cannot drift.
 */

import { readFileSync, writeFileSync, existsSync, rmSync, mkdirSync, copyFileSync } from 'node:fs';

/* The banner names the package. Read it rather than repeat it — a rename should
 * be one edit, not a search. */
const PKG_NAME = JSON.parse(readFileSync('package.json', 'utf8')).name;

const TOKENS = 'build/tokens/css/tokens.css';
const COMPONENTS = 'dist/components.css';
const FONTS_OUT = 'dist/fonts';

/*
 * The npm package each family lives in. A family named by a token with no entry
 * here is a hard failure rather than a silent fallback — see below.
 */
const FAMILY_PACKAGES = {
  'Instrument Sans': '@fontsource/instrument-sans',
  'Schibsted Grotesk': '@fontsource/schibsted-grotesk',
  Caveat: '@fontsource/caveat',
};

const fail = (m) => {
  console.error(`\x1b[31mbundle-css: ${m}\x1b[0m`);
  process.exit(1);
};

if (!existsSync(TOKENS)) {
  fail(`${TOKENS} is missing. Run \`npm run build:tokens\` first — a library built `
    + 'without it ships CSS referencing custom properties nobody defines.');
}

const tokens = readFileSync(TOKENS, 'utf8');

/*
 * Vite emits no CSS asset at all when no component imported any. That is not a
 * warning, it is a package that installs and renders nothing — so it fails here
 * rather than shipping.
 */
if (!existsSync(COMPONENTS)) {
  fail(`${COMPONENTS} is missing. Vite emitted no stylesheet, which means no component `
    + 'CSS reached the bundle. The package would install and render unstyled.');
}

const components = readFileSync(COMPONENTS, 'utf8');

const banner = (what) =>
  `/*! ${PKG_NAME} — ${what}\n`
  + ` * Generated by scripts/bundle-css.mjs. Do not edit.\n`
  + ` */\n`;

/*
 * Faces first, then tokens, then components. The @font-face rules have to be
 * declared before anything asks for the family — and the woff2 files themselves
 * are separate, so a browser fetches only the weights a page actually renders.
 */
const fontFaces = shipFonts();

writeFileSync(
  'dist/styles.css',
  `${banner('typefaces, tokens and components')}${fontFaces}\n${tokens}\n${components}`,
);
writeFileSync('dist/tokens.css', `${banner('tokens only')}${fontFaces}\n${tokens}`);

/* The intermediate is not part of the surface, and leaving it in the tarball
 * would give a consumer a second stylesheet that looks importable and renders
 * nothing. */
rmSync(COMPONENTS);

/* ── The typefaces the tokens ask for ────────────────────────────────────── */

/**
 * Every (family, weight) named by a composite font token.
 *
 * Read from the built tokens, so it is whatever design actually exported. A
 * family that appears in a token and nowhere in a component still ships — the
 * token is the contract, and a consumer building their own components against
 * these tokens needs the face as much as ours do.
 */
function facesTheTokensAsk() {
  const css = readFileSync(TOKENS, 'utf8');
  const faces = new Map();
  for (const [, weight, family] of css.matchAll(
    /--font-[a-z0-9-]+:\s*(\d{3})\s+[\d.]+px\/[\d.]+px\s+"([^"]+)"/gi,
  )) {
    faces.set(`${family}|${weight}`, { family, weight });
  }
  return [...faces.values()].sort((a, b) =>
    a.family.localeCompare(b.family) || a.weight - b.weight);
}

function shipFonts() {
  const faces = facesTheTokensAsk();
  if (!faces.length) {
    fail('no composite font tokens found. Either the token build is wrong, or this '
      + 'check has stopped matching the format it produces — both are worse than a missing font.');
  }

  mkdirSync(FONTS_OUT, { recursive: true });
  const rules = [];
  let bytes = 0;

  for (const { family, weight } of faces) {
    const pkg = FAMILY_PACKAGES[family];
    if (!pkg) {
      fail(`a token names "${family}" and this build has no package for it. Add it to `
        + 'FAMILY_PACKAGES, or the package ships a stylesheet naming a face it does not carry — '
        + 'which fails as unstyled text rather than as an error.');
    }
    const slug = pkg.split('/')[1];
    const src = `node_modules/${pkg}/files/${slug}-latin-${weight}-normal.woff2`;
    if (!existsSync(src)) {
      fail(`${src} is missing. The tokens ask for ${family} ${weight}; @fontsource does not `
        + 'have it at that weight, or the package is not installed.');
    }
    const name = `${slug}-${weight}.woff2`;
    copyFileSync(src, `${FONTS_OUT}/${name}`);
    bytes += readFileSync(src).length;

    rules.push(
      `@font-face {`,
      `  font-family: "${family}";`,
      `  font-style: normal;`,
      `  font-weight: ${weight};`,
      /* `swap` on purpose: text should be readable while the face loads. The
       * alternative is invisible text, which is the failure this whole change
       * exists to stop. */
      `  font-display: swap;`,
      `  src: url("./fonts/${name}") format("woff2");`,
      `}`,
      '',
    );
  }

  console.log(`  dist/fonts/       ${faces.length} faces, ${(bytes / 1024).toFixed(1)} kB `
    + `(${[...new Set(faces.map((f) => f.family))].join(', ')})`);
  return rules.join('\n');
}

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} kB`;
console.log(`  dist/styles.css   ${kb(fontFaces + tokens + components)}  (faces ${kb(fontFaces)} + tokens ${kb(tokens)} + components ${kb(components)})`);
console.log(`  dist/tokens.css   ${kb(fontFaces + tokens)}`);
