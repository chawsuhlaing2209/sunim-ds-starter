// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';

import site from './reference.config.json' with { type: 'json' };

/*
 * The Sunim Design System reference site.
 *
 * A separate package on purpose. Astro brings its own Vite, its own build
 * pipeline and roughly 370 packages; the design system ships four components and
 * a token build. Merging the two dependency trees would put every one of those
 * packages one `npm install` away from the thing being documented, and pin two
 * Vite majors against each other. `docs/` installs its own and stays out of the
 * way — nothing here can reach `src/index.ts`, which is the surface being
 * promised.
 *
 * The split it enforces is also the honest one:
 *
 *   Storybook  — where components *render*. Every variant, every state, live.
 *   This site  — where components are *explained*. When to use one, when not to,
 *                what it promises, which tokens it needs.
 *
 * Pages embed and deep-link into Storybook rather than re-rendering anything
 * themselves. Nothing in this package imports a component, so there is no second
 * rendering to keep in step with the first.
 *
 * The embeds are subject to Storybook's `frame-ancestors 'self'`. That directive
 * stays: the fix for a cross-origin deployment is to name this site's origin in
 * it, never `*` and never removing it. `help/embedding` has the detail, and every
 * frame carries a direct link so a blocked one costs a click rather than the
 * content.
 */
export default defineConfig({
  site: site.siteUrl,
  /*
   * Astro defaults to 4321 and does not read PORT on its own, so a harness that
   * assigns a port has no way to tell it — two servers then fight over one
   * number and the second one simply fails to start. Reading it here covers
   * `dev` and `preview` both.
   *
   * Nothing depends on this site being at a particular port: no OAuth callback,
   * no webhook, no origin allowlisted against it. The Storybook URL it embeds is
   * configured separately in reference.config.json.
   */
  server: { port: Number(process.env.PORT) || 4321 },
    /*
     * The URLs this site used before the pages were regrouped.
     *
     * Every one of these returned 200 the day they were moved, and at least
     * four of them are written into the registry as a component's `Astro
     * Link` — the cell that lets the `Development` formula derive `Released`.
     * Moving a page is a decision this repository gets to make; breaking a
     * link somebody else recorded is not, and a 404 is a poor way to tell them.
     *
     * These stay. There is no expiry on them and no plan to remove them: the
     * cost is a handful of redirect pages in the build, and the thing they buy
     * is that a URL pasted into a message a year ago still lands somewhere
     * useful. `start/what-this-is` no longer has a page at all — its content
     * became the home page and half of help/contributing — so it redirects to
     * the home page rather than to a near-match that would be a lie.
     *
     * The component names are written out rather than derived, and the list is
     * closed rather than merely current. Only a URL that was once live needs a
     * redirect, and the last `/components/<name>/` URL this site ever served was
     * one of these four. A component added tomorrow has no old address to
     * forward from, so nothing here has to know about it — which is why this is
     * a fixed list and not a generated one.
     */
    redirects: {
      '/components': '/core/components/overview/',
      '/components/overview': '/core/components/overview/',
      '/components/button': '/core/components/button/',
    '/components/chip': '/core/components/chip/',
    '/components/eyebrow': '/core/components/eyebrow/',
    '/components/iconslot': '/core/components/iconslot/',
      '/start': '/get-started/changelog/',
      '/start/tokens': '/core/tokens/',
      '/start/versioning': '/get-started/versioning/',
      '/start/embedding': '/help/embedding/',
      '/start/what-this-is': '/',
    },
  integrations: [
    starlight({
      title: site.title,
      description: site.description,
      social: [{ icon: 'github', label: 'GitHub', href: site.repoUrl }],
      /*
       * Written out rather than autogenerated, on purpose.
       *
       * The groups are the five things somebody arrives here to do — design it,
       * build it, look it up, style it, get unstuck — and a directory listing
       * cannot express that order. Naming each page also means a missing one
       * fails the build instead of quietly vanishing from the nav, which is the
       * failure mode that matters: a page nobody can reach and nobody notices.
       *
       * `core/components` is the exception and stays autogenerated, because its
       * contents are generated too — a component added to the surface has to
       * appear here without anybody editing this file.
       */
      sidebar: [
        {
          label: 'Get Started',
          items: [
            'get-started/changelog',
            'get-started/roadmap',
            'get-started/news',
            'get-started/versioning',
          ],
        },
        {
          label: 'Designing',
          items: ['designing/introduction'],
        },
        {
          label: 'Developing',
          items: [
            'developing/introduction',
            'developing/react',
            'developing/react-router',
          ],
        },
        {
          label: 'Skills',
          badge: { text: 'Soon', variant: 'caution' },
          items: ['skills/component-recommender'],
        },
        {
          label: 'Core',
          items: [
            { label: 'Components', items: [{ autogenerate: { directory: 'core/components' } }] },
            'core/tokens',
          ],
        },
        {
          label: 'Styling',
          items: ['styling/theming'],
        },
        {
          label: 'Help',
          items: [
            'help/faq',
            'help/bug-report',
            'help/feature-request',
            'help/contributing',
            'help/embedding',
          ],
        },
      ],
      /*
       * Order matters. The generated token sheet has to define the custom
       * properties before reference.css maps Starlight's variables onto them,
       * and the typefaces have to be declared before either.
       *
       * Self-hosted, never a CDN: the deployed CSP sets `font-src 'self' data:`,
       * so a Google Fonts link fails it — and fails silently, leaving every
       * label in a fallback face and every width wrong for a reason that has
       * nothing to do with the page.
       */
      customCss: [
        '@fontsource/instrument-sans/400.css',
        '@fontsource/instrument-sans/500.css',
        '@fontsource/instrument-sans/600.css',
        '@fontsource/instrument-sans/700.css',
        '@fontsource/schibsted-grotesk/600.css',
        '@fontsource/schibsted-grotesk/700.css',
        '@fontsource/schibsted-grotesk/800.css',
        './src/styles/tokens.generated.css',
        './src/styles/reference.css',
      ],
      lastUpdated: true,
    }),
  ],
});
